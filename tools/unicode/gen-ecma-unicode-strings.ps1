<#
.SYNOPSIS
    Writes EcmaRegexUnicodeStrings<major>.cs, the data behind the properties of strings that a pattern with the v flag may
    name (\p{RGI_Emoji} and the six it is the union of), from the two emoji sequence files of the Unicode Character
    Database.

.DESCRIPTION
    ECMA-262 (the v flag, "UnicodeSets") lets \p{...} name seven properties of strings: Basic_Emoji,
    Emoji_Keycap_Sequence, RGI_Emoji_Modifier_Sequence, RGI_Emoji_Flag_Sequence, RGI_Emoji_Tag_Sequence,
    RGI_Emoji_ZWJ_Sequence and RGI_Emoji, which is the union of the other six. The first five are in
    emoji-sequences.txt and the sixth in emoji-zwj-sequences.txt. Basic_Emoji has single code points (written
    alone or as a range) as well as sequences; the others hold sequences only.

    Each property is written as two texts: its single code points as hexadecimal ranges, and its sequences as
    hexadecimal code points, a space between the code points of a sequence and a semicolon between sequences.
    UnicodeTables reads a property the first time a pattern names it.

.PARAMETER EmojiSequences
    The path of emoji-sequences.txt.

.PARAMETER EmojiZwjSequences
    The path of emoji-zwj-sequences.txt.

.PARAMETER ClassName
    The name of the class to write: EcmaRegexUnicodeStrings followed by the major version of the emoji files
    (EcmaRegexUnicodeStrings17), one class for each version of Unicode the library carries.

.PARAMETER Output
    The file to write. The default is <ClassName>.cs in the library's Unicode directory.

.EXAMPLE
    pwsh gen-ecma-unicode-strings.ps1 -EmojiSequences ./emoji-sequences.txt -EmojiZwjSequences ./emoji-zwj-sequences.txt
#>
param(
    [Parameter(Mandatory = $true)][string]$EmojiSequences,
    [Parameter(Mandatory = $true)][string]$EmojiZwjSequences,
    [string]$ClassName = '',
    [string]$Output = ''
)

$ErrorActionPreference = 'Stop'

$properties = [ordered]@{
    Basic_Emoji                 = 'BasicEmoji'
    Emoji_Keycap_Sequence       = 'EmojiKeycapSequence'
    RGI_Emoji_Modifier_Sequence = 'RgiEmojiModifierSequence'
    RGI_Emoji_Flag_Sequence     = 'RgiEmojiFlagSequence'
    RGI_Emoji_Tag_Sequence      = 'RgiEmojiTagSequence'
    RGI_Emoji_ZWJ_Sequence      = 'RgiEmojiZwjSequence'
}
$codePoints = @{}
$sequences = @{}
$versions = @{}
foreach ($name in $properties.Keys) {
    $codePoints[$name] = [System.Collections.Generic.List[string]]::new()
    $sequences[$name] = [System.Collections.Generic.List[string]]::new()
}

foreach ($file in @($EmojiSequences, $EmojiZwjSequences)) {
    foreach ($line in [System.IO.File]::ReadLines((Resolve-Path $file))) {
        if ($line -match '^# Version: (.*)$') { $versions[$file] = $Matches[1].Trim(); continue }
        $text = ($line -split '#', 2)[0].Trim()
        if ($text -eq '') { continue }
        $fields = $text -split ';'
        $value = $fields[0].Trim()
        $name = $fields[1].Trim()
        if (-not $properties.Contains($name)) { throw "Unknown property $name in $file." }
        if ($value -match '^([0-9A-F]+)\.\.([0-9A-F]+)$') {
            $codePoints[$name].Add("$($Matches[1])..$($Matches[2])")
        } elseif ($value -match '^[0-9A-F]+$') {
            $codePoints[$name].Add($value)
        } elseif ($value -match '^[0-9A-F]+( [0-9A-F]+)+$') {
            $sequences[$name].Add(($value -split ' +') -join ' ')
        } else {
            throw "Unreadable value '$value' in $file."
        }
    }
}

if ($versions.Count -ne 2 -or ($versions.Values | Select-Object -Unique).Count -ne 1) { throw 'The two files have no version, or not the same one.' }
$version = $versions.Values | Select-Object -First 1
foreach ($name in $properties.Keys) {
    if ($name -ne 'Basic_Emoji' -and $codePoints[$name].Count -ne 0) { throw "$name has single code points, and only Basic_Emoji may." }
    if ($sequences[$name].Count -eq 0) { throw "$name has no sequences." }
}

$out = [System.Text.StringBuilder]::new()
function Add-Line([string]$line = '') { [void]$out.Append($line).Append("`n") }

# A long text as a constant of concatenated lines.
function Add-Text([string]$declaration, [string]$text) {
    Add-Line "    $declaration"
    $width = 110
    for ($k = 0; $k -lt $text.Length; $k += $width) {
        $piece = $text.Substring($k, [Math]::Min($width, $text.Length - $k))
        $end = if ($k + $width -ge $text.Length) { ';' } else { ' +' }
        Add-Line "        `"$piece`"$end"
    }
}

if (-not $ClassName) { $ClassName = 'EcmaRegexUnicodeStrings' + $version.Split('.')[0] }
if (-not $Output) { $Output = Join-Path $PSScriptRoot '..' '..' 'Solutions' 'Corvus.Regex.Ecma262' 'Unicode' "$ClassName.cs" }
Add-Line "// <copyright file=`"$ClassName.cs`" company=`"Endjin Limited`">"
Add-Line '// Copyright (c) Endjin Limited. All rights reserved.'
Add-Line '// </copyright>'
Add-Line
Add-Line "// Generated by tools/unicode/gen-ecma-unicode-strings.ps1 from emoji-sequences.txt and emoji-zwj-sequences.txt of"
Add-Line "// Unicode $version."
Add-Line '// DO NOT EDIT.'
Add-Line '// <auto-generated/>'
Add-Line '#nullable enable'
Add-Line
Add-Line 'namespace Corvus.Ecma262.RegularExpressions;'
Add-Line
Add-Line '/// <summary>'
Add-Line "/// The data behind the properties of strings a pattern with the v flag may name, of Unicode $version, which"
Add-Line '/// <see cref="UnicodeTables"/> reads: for each property its single code points as hexadecimal ranges, and its'
Add-Line '/// sequences as hexadecimal code points with a space between the code points of a sequence and a semicolon between'
Add-Line '/// sequences.'
Add-Line '/// </summary>'
Add-Line "internal static class $ClassName"
Add-Line '{'
Add-Line '    /// <summary>The Unicode version of the data.</summary>'
Add-Line "    public const string UnicodeVersion = `"$version`";"
Add-Line
Add-Line '    /// <summary>The names of the properties of strings, each of which is one of <see cref="RGI_Emoji"/>, in the order of the tables.</summary>'
Add-Line '    public static readonly string[] Names = ['
Add-Line ("        " + (($properties.Keys | ForEach-Object { "`"$_`"" }) -join ', ') + ',')
Add-Line '    ];'
Add-Line
Add-Line '    /// <summary>The name of the union of them all.</summary>'
Add-Line '    public const string RGI_Emoji = "RGI_Emoji";'
$k = 0
foreach ($name in $properties.Keys) {
    $id = $properties[$name]
    Add-Line
    Add-Line "    /// <summary>The single code points of $name, as ranges ($($codePoints[$name].Count) of them).</summary>"
    if ($codePoints[$name].Count -eq 0) {
        Add-Line "    public const string ${id}CodePoints = `"`";"
    } else {
        Add-Text "public const string ${id}CodePoints =" ($codePoints[$name] -join ' ')
    }
    Add-Line
    Add-Line "    /// <summary>The sequences of $name ($($sequences[$name].Count) of them).</summary>"
    Add-Text "public const string ${id}Sequences =" ($sequences[$name] -join ';')
    $k++
}
Add-Line
Add-Line '    /// <summary>The single code points of a property, by its index in <see cref="Names"/>.</summary>'
Add-Line '    /// <param name="index">The index.</param>'
Add-Line '    /// <returns>The text.</returns>'
Add-Line '    public static string CodePoints(int index) => index switch'
Add-Line '    {'
$k = 0
foreach ($name in $properties.Keys) { Add-Line "        $k => $($properties[$name])CodePoints,"; $k++ }
Add-Line '        _ => throw new System.ArgumentOutOfRangeException(nameof(index)),'
Add-Line '    };'
Add-Line
Add-Line '    /// <summary>The sequences of a property, by its index in <see cref="Names"/>.</summary>'
Add-Line '    /// <param name="index">The index.</param>'
Add-Line '    /// <returns>The text.</returns>'
Add-Line '    public static string Sequences(int index) => index switch'
Add-Line '    {'
$k = 0
foreach ($name in $properties.Keys) { Add-Line "        $k => $($properties[$name])Sequences,"; $k++ }
Add-Line '        _ => throw new System.ArgumentOutOfRangeException(nameof(index)),'
Add-Line '    };'
Add-Line '}'

[System.IO.File]::WriteAllText($Output, $out.ToString().TrimEnd("`n"), [System.Text.UTF8Encoding]::new($false))
$total = 0
foreach ($name in $properties.Keys) { $total += $sequences[$name].Count }
Write-Host "Wrote $Output (Unicode $version, $total sequences)."
