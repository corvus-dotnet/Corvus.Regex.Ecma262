<#
.SYNOPSIS
    Writes Es2020Properties.cs, the Unicode property names and values that the grammar of ECMAScript 2020 knows, from
    es2020-properties.json of the test data.

.DESCRIPTION
    ECMAScript 2020 (ECMA-262, 11th edition) closes the names a \p{...} escape may use: an implementation "must not
    support" names other than those of its tables of non-binary properties, binary properties, General_Category values
    and Script values (section 21.2.2.8.4). es2020-properties.json of the test data repository
    (corvus-dotnet/ecma262-regex-test-data) holds every name and alias of those four tables, taken from tc39/ecma262
    at the tag es2020. The test data's edition overlay is made from the same file, so the parser and the data agree.

.PARAMETER Properties
    The path of es2020-properties.json.

.PARAMETER Output
    The file to write. The default is Es2020Properties.cs in the library's Unicode directory.

.EXAMPLE
    pwsh gen-es2020-properties.ps1 -Properties ../ecma262-regex-test-data/es2020-properties.json
#>
param(
    [Parameter(Mandatory = $true)][string]$Properties,
    [string]$Output = ''
)

$ErrorActionPreference = 'Stop'

if (-not $Output) {
    $Output = Join-Path $PSScriptRoot '../../Solutions/Corvus.Regex.Ecma262/Unicode/Es2020Properties.cs'
}

$tables = Get-Content -Raw (Resolve-Path $Properties) | ConvertFrom-Json

function Write-Names([System.Text.StringBuilder]$sb, [string]$field, [string]$summary, [object[]]$names) {
    [void]$sb.AppendLine("    /// <summary>$summary</summary>")
    [void]$sb.AppendLine("    private static readonly HashSet<string> $field = new(StringComparer.Ordinal)")
    [void]$sb.AppendLine('    {')
    [string[]]$sorted = @($names)
    [Array]::Sort($sorted, [StringComparer]::Ordinal)
    foreach ($name in $sorted) {
        [void]$sb.AppendLine("        `"$name`",")
    }

    [void]$sb.AppendLine('    };')
}

$sb = [System.Text.StringBuilder]::new()
[void]$sb.AppendLine('// <copyright file="Es2020Properties.cs" company="Endjin Limited">')
[void]$sb.AppendLine('// Copyright (c) Endjin Limited. All rights reserved.')
[void]$sb.AppendLine('// </copyright>')
[void]$sb.AppendLine('// <auto-generated>')
[void]$sb.AppendLine('// Written by tools/unicode/gen-es2020-properties.ps1 from es2020-properties.json of the test data. Do not edit.')
[void]$sb.AppendLine('// </auto-generated>')
[void]$sb.AppendLine()
[void]$sb.AppendLine('using System;')
[void]$sb.AppendLine('using System.Collections.Generic;')
[void]$sb.AppendLine()
[void]$sb.AppendLine('namespace Corvus.Ecma262.RegularExpressions;')
[void]$sb.AppendLine()
[void]$sb.AppendLine('/// <summary>')
[void]$sb.AppendLine('/// The Unicode property names and values of the tables of ECMAScript 2020 (ECMA-262, 11th edition), the only ones its')
[void]$sb.AppendLine('/// grammar knows whatever the version of Unicode: tc39/ecma262 at the tag es2020, every name and alias of each.')
[void]$sb.AppendLine('/// </summary>')
[void]$sb.AppendLine('internal static class Es2020Properties')
[void]$sb.AppendLine('{')
Write-Names $sb 'NonBinary' 'The non-binary properties.' $tables.nonbinary
[void]$sb.AppendLine()
Write-Names $sb 'BinaryNames' 'The binary properties.' $tables.binary
[void]$sb.AppendLine()
Write-Names $sb 'Categories' 'The values of General_Category.' $tables.general_category
[void]$sb.AppendLine()
Write-Names $sb 'Scripts' 'The values of Script and Script_Extensions.' $tables.script
[void]$sb.AppendLine()
[void]$sb.AppendLine('    /// <summary>')
[void]$sb.AppendLine('    /// Whether the expression between the braces of <c>\p{...}</c> names a property, and a value of it, of the tables:')
[void]$sb.AppendLine('    /// a name and a value joined by <c>=</c>, or the lone name of a General_Category value or of a binary property.')
[void]$sb.AppendLine('    /// </summary>')
[void]$sb.AppendLine('    /// <param name="expression">The expression.</param>')
[void]$sb.AppendLine('    /// <returns><see langword="true"/> when it does.</returns>')
[void]$sb.AppendLine('    public static bool Has(ReadOnlySpan<char> expression)')
[void]$sb.AppendLine('    {')
[void]$sb.AppendLine('        int eq = expression.IndexOf(''='');')
[void]$sb.AppendLine('        if (eq < 0)')
[void]$sb.AppendLine('        {')
[void]$sb.AppendLine('            string lone = expression.ToString();')
[void]$sb.AppendLine('            return Categories.Contains(lone) || BinaryNames.Contains(lone);')
[void]$sb.AppendLine('        }')
[void]$sb.AppendLine()
[void]$sb.AppendLine('        string name = expression.Slice(0, eq).ToString();')
[void]$sb.AppendLine('        string value = expression.Slice(eq + 1).ToString();')
[void]$sb.AppendLine('        if (!NonBinary.Contains(name))')
[void]$sb.AppendLine('        {')
[void]$sb.AppendLine('            return false;')
[void]$sb.AppendLine('        }')
[void]$sb.AppendLine()
[void]$sb.AppendLine('        return name == "General_Category" || name == "gc" ? Categories.Contains(value) : Scripts.Contains(value);')
[void]$sb.AppendLine('    }')
[void]$sb.Append('}')

[System.IO.File]::WriteAllText([System.IO.Path]::GetFullPath($Output), $sb.ToString().Replace("`r`n", "`n"))
Write-Host "Wrote $Output"
